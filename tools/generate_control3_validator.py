#!/usr/bin/env python3
"""Generate private control3 request validators; frozen schema is the source."""
import json
import re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
schema=json.loads((root/'interfaces/0.3.0/schemas/runtime-3.0.schema.json').read_text())
out=['/* Generated by tools/generate_control3_validator.py. Copyright 2026 Hans-Einar. MIT. */']
cache={}
def emit(s):
 if '$ref' in s:s=schema['$defs'][s['$ref'].split('/')[-1]]
 key=json.dumps(s,sort_keys=True)
 if key in cache:return cache[key]
 name=f'wire3_validate_{len(cache)}';cache[key]=name
 lines=[]
 if 'oneOf' in s:
  funcs=[emit(x) for x in s['oneOf']];lines+=['return '+' || '.join(f'{f}(d,t)' for f in funcs)+';']
 elif 'const' in s:
  v=s['const'];lines+=['return '+('wire_string_is(d,t,'+json.dumps(v)+')' if isinstance(v,str) else 'wire3_literal(d,t,'+json.dumps(str(v).lower())+')')+';']
 elif 'enum' in s:
  lines+=['return '+' || '.join('wire_string_is(d,t,'+json.dumps(x)+')' if isinstance(x,str) else 'wire3_literal(d,t,'+json.dumps(str(x))+')' for x in s['enum'])+';']
 elif s.get('type')=='object':
  fields=s.get('properties',{})
  if fields:
   funcs={k:emit(v) for k,v in fields.items()}
   lines+=['if(d->tokens[t].type!=JSON_OBJECT || d->tokens[t].size!='+str(len(fields)*2)+')return false;']
   lines+=['return '+' && '.join(f'{f}(d,json_member(d,t,"{k}"))' for k,f in funcs.items())+';']
  else:lines+=['return d->tokens[t].type==JSON_OBJECT;']
 elif s.get('type')=='array':
  f=emit(s['items']);lines+=['int i,j; if(d->tokens[t].type!=JSON_ARRAY || d->tokens[t].size>'+str(s['maxItems'])+' || d->tokens[t].size<'+str(s.get('minItems',0))+')return false;','for(i=t+1;i<d->count&&d->tokens[i].start<d->tokens[t].end;i=json_next(d,i)){',f'if(!{f}(d,i))return false;']
  if s.get('uniqueItems'):lines+=['for(j=t+1;j<i;j=json_next(d,j))if(wire_equal(d,i,j))return false;']
  else:lines+=['(void)j;']
  lines+=['}return true;']
 elif s.get('type')=='integer':lines+=['int64_t v; return json_integer(d,t,'+str(s['minimum'])+','+str(s['maximum'])+',&v);']
 elif s.get('type')=='null':lines+=['return wire_null(d,t);']
 elif s.get('type')=='boolean':lines+=['return wire3_literal(d,t,"true") || wire3_literal(d,t,"false");']
 elif s.get('format') in ('uint64','segment-bytes'):
  extra=' && v>0' if s.get('pattern','').startswith('^[1-9]') else ''
  if s['format']=='segment-bytes':extra+=' && v>=65536 && v<=1073741824'
  lines+=['uint64_t v;return json_u64(d,t,&v)'+extra+';']
 elif s.get('type')=='string':
  pattern=s.get('pattern','')
  if pattern=='^[0-9a-f]{32}$':lines+=['char v[33];return json_string(d,t,v,sizeof v)&&hex_string(v,32);']
  elif pattern:
   maximum=int(re.search(r'1,(\d+)',pattern)[1]);lines+=['char v['+str(maximum+1)+']={0};return json_string(d,t,v,sizeof v)&&identifier(v,sizeof v,false);']
  else:lines+=['char v['+str(s.get('maxLength',64)+1)+'];return json_string(d,t,v,sizeof v);']
 else:raise Exception(s)
 out.append('static bool '+name+'(const struct json_document *d,int t) {\nif(t<0||t>=d->count)return false;\n'+'\n'.join(lines)+'\n}')
 return name
commands=[]
for x in schema['oneOf']:
 if x['properties']['type']['const']!='request':continue
 cmd=x['properties']['command']['const'];args=x['properties']['arguments']
 if cmd=='hello':
  args['properties']['contractVersion']={'type':'string','maxLength':64}
  args['properties']['protocol']['properties']={k:{'type':'integer','minimum':0,'maximum':4294967295} for k in ('major','minor')}
 commands.append((cmd,emit(args)))
out.append('static bool wire3_arguments(const struct json_document *d,int t,const char *command) {\n'+'\n'.join(f'if(!strcmp(command,"{c}"))return {f}(d,t);' for c,f in commands)+'\nreturn false;\n}')
out.append('static bool wire3_command(const char *command) { return '+' || '.join(f'!strcmp(command,"{c}")' for c,f in commands)+';}')
(root/'emu_control3_schema_internal.h').write_text('\n'.join(out)+'\n')
