#!/usr/bin/env python3
"""Generate private request validators from the immutable wire schema."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
schema=json.loads((root/'interfaces/0.2.0/schemas/runtime-2.1.schema.json').read_text())
out=['/* Generated by tools/generate_wire_validator.py. Copyright 2026 Hans-Einar. MIT. */']
counter=0

def emit(s):
 global counter
 n=counter;counter+=1;name=f'wire_validate_{n}'
 lines=[]
 if 'oneOf' in s:
  funcs=[emit(x) for x in s['oneOf']];lines+=['return '+' || '.join(f'{f}(d,t)' for f in funcs)+';']
 elif s.get('type')=='object':
  fields=s.get('properties',{})
  if fields:
   funcs={k:emit(v) for k,v in fields.items()}
   lines+=['if(d->tokens[t].type!=JSON_OBJECT || d->tokens[t].size!='+str(len(fields)*2)+')return false;']
   lines+=['return '+' && '.join(f'{f}(d,json_member(d,t,"{k}"))' for k,f in funcs.items())+';']
  else:lines+=['return d->tokens[t].type==JSON_OBJECT;']
 elif s.get('type')=='array':
  f=emit(s['items']);lines+=['int i,j; if(d->tokens[t].type!=JSON_ARRAY || d->tokens[t].size>'+str(s['maxItems'])+')return false;','for(i=t+1;i<d->count&&d->tokens[i].start<d->tokens[t].end;i=json_next(d,i)){',f'if(!{f}(d,i))return false;']
  if s.get('uniqueItems'):lines+=['for(j=t+1;j<i;j=json_next(d,j))if(wire_equal(d,i,j))return false;']
  else:lines+=['(void)j;']
  lines+=['}return true;']
 elif s.get('type')=='integer':lines+=['int64_t v; return json_integer(d,t,'+str(s['minimum'])+','+str(s['maximum'])+',&v);']
 elif s.get('type')=='null':lines+=['return wire_null(d,t);']
 elif 'const' in s:
  v=s['const']
  if isinstance(v,str):lines+=['return wire_string_is(d,t,'+json.dumps(v)+');']
  else:lines+=['int64_t v;return json_integer(d,t,0,UINT32_MAX,&v);'] # hello mismatches get VERSION
 elif 'enum' in s:lines+=['return '+' || '.join('wire_string_is(d,t,'+json.dumps(x)+')' for x in s['enum'])+';']
 elif s.get('format')=='uint64':lines+=['uint64_t v;return json_u64(d,t,&v);']
 elif s.get('type')=='string':
  if '32' in s.get('pattern',''):lines+=['char v[33];return json_string(d,t,v,sizeof v)&&hex_string(v,32);']
  else:lines+=['char v[64]={0};return json_string(d,t,v,sizeof v)&&identifier(v,sizeof v,false);']
 else:raise Exception(s)
 out.append('static bool '+name+'(const struct json_document *d,int t) {\nif(t<0||t>=d->count)return false;\n'+'\n'.join(lines)+'\n}')
 return name
commands=[]
for x in schema['oneOf']:
 if x['properties']['type']['const']!='request':continue
 cmd=x['properties']['command']['const'];args=x['properties']['arguments']
 if cmd=='hello':
  args['properties']['contractVersion']={'type':'string'}
  args['properties']['requiredCapabilities']['items']={'type':'string'}
 commands.append((cmd,emit(args)))
out.append('static bool wire_arguments(const struct json_document *d,int t,const char *command) {\n'+'\n'.join(f'if(!strcmp(command,"{c}"))return {f}(d,t);' for c,f in commands)+'\nreturn false;\n}')
out.append('static bool wire_command(const char *command) { return '+' || '.join(f'!strcmp(command,"{c}")' for c,f in commands)+';}')
(root/'emu_wire_schema_internal.h').write_text('\n'.join(out)+'\n')
